    AND object_id = OBJECT_ID(N'[dbo].[sys_data_dictionary]') AND is_unique_constraint = 1)
    ALTER TABLE sys_data_dictionary DROP CONSTRAINT uk_sys_dict_type_code;

-- 创建非唯一索引以替代原唯一约束(便于按类型+编码查询)
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'ix_sys_dict_type_code'
    AND object_id = OBJECT_ID(N'[dbo].[sys_data_dictionary]'))
    CREATE INDEX ix_sys_dict_type_code ON sys_data_dictionary(dict_type, dict_code);

